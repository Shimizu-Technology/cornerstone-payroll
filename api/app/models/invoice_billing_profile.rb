# frozen_string_literal: true

class InvoiceBillingProfile < ApplicationRecord
  LEGACY_DEFAULT_FOOTER = "Generated by Cornerstone Payroll."
  DEFAULT_FOOTER = "Thank you for your business."
  belongs_to :organization
  has_many :invoices, dependent: :restrict_with_error
  has_many :invoice_number_sequences, dependent: :restrict_with_error

  before_validation :normalize_blanks
  before_save :clear_other_defaults, if: :is_default?
  include FinanceBookOwned

  validates :numbering_style, inclusion: { in: %w[yearly continuing] }
  validates :invoice_theme, inclusion: { in: InvoicePdf::Style::THEMES, message: "must be Classic, Modern, Professional or Banner" }
  validates :logo_size, inclusion: { in: InvoicePdf::Style::LOGO_SIZES, message: "must be small, medium or large" }
  validates :accent_color, format: { with: InvoicePdf::Style::HEX_COLOR, message: "must be a hex color like #1F4E79" },
                           allow_nil: true
  validates :show_service_period, :show_item_column, :show_how_to_pay, inclusion: { in: [ true, false ] }
  validates :next_invoice_number, numericality: { only_integer: true, greater_than: 0 }
  validates :invoice_number_width, numericality: { only_integer: true, in: 1..12 }, allow_nil: true
  validate :valid_service_catalog

  validates :name, presence: true, uniqueness: { scope: :finance_book_id }
  validates :invoice_prefix, length: { maximum: 16 }, allow_blank: true
  validates :logo_content_type, inclusion: { in: InvoiceLogoStorageService::CONTENT_TYPES }, allow_nil: true
  validates :logo_byte_size, numericality: { only_integer: true, greater_than: 0,
                                             less_than_or_equal_to: InvoiceLogoStorageService::MAX_BYTES }, allow_nil: true
  validate :logo_fields_are_complete

  scope :active, -> { where(active: true) }
  scope :ordered, -> { order(Arel.sql("is_default DESC"), :name, :id) }

  def self.ensure_default_for!(organization, finance_book: nil)
    organization.with_lock do
      finance_book ||= organization.finance_books.first if organization.finance_books.one?
      raise ArgumentError, "Select a financial book" unless finance_book&.organization_id == organization.id

      profiles = finance_book.invoice_billing_profiles
      profiles.where(active: false, is_default: true).update_all(is_default: false)

      existing_default = profiles.active.where(is_default: true).order(:id).first
      if existing_default
        existing_default.update!(footer_note: DEFAULT_FOOTER) if existing_default.footer_note == LEGACY_DEFAULT_FOOTER
        return existing_default
      end

      existing_active = profiles.active.order(:id).first
      if existing_active
        existing_active.update!(is_default: true, footer_note: refreshed_footer(existing_active.footer_note))
        return existing_active
      end

      # Firm contact details come from a live client only, never a demo or practice copy.
      primary_company = organization.primary_company if organization.primary_company&.live_payroll?
      primary_company ||= organization.companies.live_payroll.order(:id).first
      profile = profiles.find_or_initialize_by(name: finance_book.name)
      profile.update!(
        organization: organization,
        legal_name: profile.legal_name.presence || finance_book.legal_name,
        phone: profile.phone.presence || primary_company&.phone,
        email: profile.email.presence || primary_company&.email,
        address: profile.address.presence || company_address(primary_company),
        invoice_prefix: profile.invoice_prefix.presence || "INV",
        remit_to: profile.remit_to.presence || finance_book.legal_name,
        footer_note: refreshed_footer(profile.footer_note),
        active: true,
        is_default: true
      )
      profile
    end
  end

  # A continuing invoice number as printed: zero-padded to
  # invoice_number_width digits when set (5: 7055 -> "07055"), never cut.
  def format_continuing_number(number)
    invoice_number_width ? number.to_s.rjust(invoice_number_width, "0") : number.to_s
  end

  # The number the next invoice from this sender would be issued with, for
  # previews only (see InvoiceNumberAllocator.preview).
  def next_number_preview(invoice_date = PayrollBusinessClock.today)
    InvoiceNumberAllocator.preview(billing_profile: self, invoice_date: invoice_date)
  end

  # The look new invoices from this sender get. Issued invoices keep the
  # style recorded in their snapshot.
  def invoice_style
    InvoicePdf::Style.from_profile(self)
  end

  def self.company_address(company)
    return nil unless company

    [
      company.address_line1,
      company.address_line2,
      [ company.city, company.state, company.zip ].compact_blank.join(", ").presence
    ].compact_blank.join("\n").presence
  end

  def self.refreshed_footer(value)
    value.blank? || value == LEGACY_DEFAULT_FOOTER ? DEFAULT_FOOTER : value
  end

  private

  def valid_service_catalog
    valid = service_catalog.is_a?(Array) && service_catalog.size <= 50 && service_catalog.all? do |entry|
      entry.is_a?(Hash) && entry["name"].is_a?(String) && entry["name"].present? &&
        entry["description_template"].is_a?(String) && entry["description_template"].present? &&
        entry["line_kind"].in?(%w[service_fee reimbursement])
    end
    errors.add(:service_catalog, "must contain up to 50 named services with a description template and valid line kind") unless valid
  end

  def logo_fields_are_complete
    fields = [ logo_storage_key, logo_content_type, logo_sha256, logo_byte_size ]
    return if fields.all?(&:blank?) || fields.all?(&:present?)

    errors.add(:logo_storage_key, "must include complete logo metadata")
  end

  def normalize_blanks
    self.name = name.to_s.strip
    self.legal_name = legal_name.to_s.strip.presence
    self.website = website.to_s.strip.presence
    self.phone = phone.to_s.strip.presence
    self.email = email.to_s.strip.presence
    self.address = address.to_s.strip.presence
    self.payment_instructions = payment_instructions.to_s.strip.presence
    self.default_payment_terms = default_payment_terms.to_s.strip.presence
    self.invoice_prefix = invoice_prefix.to_s.strip.presence
    self.remit_to = remit_to.to_s.strip.presence
    self.footer_note = footer_note.to_s.strip.presence
    self.accent_color = InvoicePdf::Style.normalize_hex(accent_color)
    self.invoice_theme = invoice_theme.to_s.strip.downcase.presence || InvoicePdf::Style::DEFAULT_THEME
    self.logo_size = logo_size.to_s.strip.downcase.presence || InvoicePdf::Style::DEFAULT_LOGO_SIZE
    self.active = true if active.nil?
    self.is_default = false unless active?
  end

  def clear_other_defaults
    self.class.where(finance_book_id: finance_book_id, is_default: true)
      .where.not(id: id)
      .update_all(is_default: false)
  end
end
